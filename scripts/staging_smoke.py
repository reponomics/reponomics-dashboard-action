def _remote_url(remote: str) -> str:
    try:
        # git is fixed; the remote is a distinct argument and is repository-checked before use.
        return subprocess.check_output(  # nosec B603, B607
            ["git", "remote", "get-url", remote],
            cwd=ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except subprocess.CalledProcessError as exc:
        if "/" in _remote_repo_path(remote):
            return remote
        raise StagingSmokeError(f"Unknown git remote or repository URL: {remote}") from exc


def _remote_repo_path(remote_url: str) -> str:
    parsed = urlparse(remote_url)
    if parsed.scheme:
        path = parsed.path
    elif ":" in remote_url and not remote_url.startswith("/"):
        path = remote_url.split(":", 1)[1]
    else:
        path = remote_url
    path = path.strip().rstrip("/")
    if path.endswith(".git"):
        path = path[:-4]
    parts = [part for part in path.split("/") if part]
    if len(parts) >= 2:
        return "/".join(parts[-2:])
    return parts[-1] if parts else ""


def _display_remote_url(remote_url: str) -> str:
    parsed = urlparse(remote_url)
    if parsed.scheme and parsed.hostname and "@" in parsed.netloc:
        host = parsed.hostname
        if parsed.port is not None:
            host = f"{host}:{parsed.port}"
        return parsed._replace(netloc=host).geturl()
    return remote_url


def _assert_expected_repo(remote_url: str, expected_repo: str) -> None:
    actual = _remote_repo_path(remote_url)
    expected = expected_repo.removesuffix(".git").strip("/")
    if "/" in expected:
        matched = actual == expected
    else:
        matched = actual == expected or actual.endswith(f"/{expected}")
    if not matched:
        raise StagingSmokeError(
            f"Remote safety check failed: expected {expected_repo}, got {actual or remote_url}"
        )


def _replace_worktree_contents(worktree: Path, output_dir: Path) -> None:
    for child in worktree.iterdir():
        if child.name == ".git":
            continue
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()
    for child in output_dir.iterdir():
        target = worktree / child.name
        if child.is_dir():
            shutil.copytree(child, target)
        else:
            shutil.copy2(child, target)


def _has_staged_changes(worktree: Path) -> bool:
    # git is the fixed executable and this command has no dynamic arguments.
    result = subprocess.run(  # nosec B603, B607
        ["git", "diff", "--cached", "--quiet"],
        cwd=worktree,
        check=False,
    )
    if result.returncode == 0:
        return False
    if result.returncode == 1:
        return True
    result.check_returncode()
    return False


def publish_staging_tree(
    output_dir: Path,
    *,
    remote: str,
    branch: str,
    message: str,
    expected_repo: str,
    push: bool,
) -> str | None:
    output_dir = output_dir.resolve()
    if not output_dir.exists():
        raise StagingSmokeError(f"Staging smoke output does not exist: {output_dir}")
    if not (output_dir / "config.yaml").is_file():
        raise StagingSmokeError("Staging smoke output is missing config.yaml")
    if not (output_dir / STAGING_RECORD).is_file():
        raise StagingSmokeError(f"Staging smoke output is missing {STAGING_RECORD}")

    remote_url = _remote_url(remote)
    _assert_expected_repo(remote_url, expected_repo)
    display_remote_url = _display_remote_url(remote_url)
    print(f"Prepared staging smoke tree at {output_dir}")
    print(f"Target: {display_remote_url} {branch}")
    if not push:
        print("Dry run only. Re-run with --push to replace the staging branch.")
        return None

    with tempfile.TemporaryDirectory(prefix="staging-smoke-repo-") as tmp:
        worktree = Path(tmp) / "repo"
        worktree.mkdir()
        _run(["git", "init", "-b", branch], worktree)
        _run(["git", "config", "user.name", "reponomics-staging[bot]"], worktree)
        _run(
            [
                "git",
                "config",
                "user.email",
                "286571062+reponomics-dashboard[bot]@users.noreply.github.com",
            ],
            worktree,
        )
        _run(["git", "remote", "add", "target", remote_url], worktree)

        remote_ref = f"refs/heads/{branch}"
        remote_oid = _output(["git", "ls-remote", "--heads", "target", branch], worktree)
        if remote_oid:
            expected_oid = remote_oid.split()[0]
            _run(["git", "fetch", "target", remote_ref], worktree)
            _run(["git", "checkout", "-B", branch, "FETCH_HEAD"], worktree)
            lease = f"--force-with-lease={remote_ref}:{expected_oid}"
        else:
            _run(["git", "checkout", "--orphan", branch], worktree)
            lease = f"--force-with-lease={remote_ref}:"

        _replace_worktree_contents(worktree, output_dir)
        _run(["git", "add", "-A"], worktree)
        if _has_staged_changes(worktree):
            _run(
                ["git", "-c", "core.hooksPath=/dev/null", "commit", "-m", message],
                worktree,
            )
        else:
            print(f"Staging smoke tree already matches target {branch}.")
        published_commit = _output(["git", "rev-parse", "HEAD"], worktree)
        _run(["git", "push", lease, "target", f"HEAD:{remote_ref}"], worktree)

    verified = _output(["git", "ls-remote", "--heads", remote_url, branch], ROOT)
    verified_commit = verified.split()[0] if verified else ""
    if verified_commit != published_commit:
        raise StagingSmokeError(
            f"Published branch verification failed: expected {published_commit}, "
            + f"got {verified_commit or 'missing'}"
        )
    print(f"Published staging smoke tree to {display_remote_url}/{branch}")
    print(f"Published commit: {published_commit}")
    return published_commit


def prepare_staging_smoke(
    *,
    output_dir: Path,
    remote: str,
    expected_repo: str,
    branch: str,
    message: str,
    repositories: list[str],
    publish_repositories: list[str],
    evidence_file: Path,
    push: bool,
) -> StagingSmokeResult:
    collect, publish = resolve_repositories(repositories, publish_repositories)
    output_dir = output_dir.resolve()
    build_template.build_template(output_dir)
    _write_staging_config(
        output_dir,
        collect_repositories=collect,
        publish_repositories=publish,
    )
    resolved_config = _validate_generated_config(output_dir)
    record = _build_record(
        output_dir=output_dir,
        remote=remote,
        expected_repo=expected_repo,
        branch=branch,
        collect_repositories=collect,
        publish_repositories=publish,
        resolved_config=resolved_config,
    )
    _write_record(output_dir, record)
    published_commit = publish_staging_tree(
        output_dir,
        remote=remote,
        branch=branch,
        message=message,
        expected_repo=expected_repo,
        push=push,
    )
    _write_evidence(evidence_file, record=record, published_commit=published_commit)
    print(f"Wrote staging smoke evidence: {evidence_file}")
    return StagingSmokeResult(
        output_dir=output_dir,
        evidence_file=evidence_file,
        published_commit=published_commit,
        record=record,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--remote", default=DEFAULT_REMOTE)
    parser.add_argument("--expected-repo", default=DEFAULT_EXPECTED_REPO)
    parser.add_argument("--branch", default=DEFAULT_BRANCH)
    parser.add_argument("--message", default=DEFAULT_MESSAGE)
    parser.add_argument("--repository", action="append", default=[])
    parser.add_argument("--publish-repository", action="append", default=[])
    parser.add_argument("--evidence", type=Path, default=DEFAULT_EVIDENCE)
    parser.add_argument("--push", action="store_true")
    args = parser.parse_args()
    prepare_staging_smoke(
        output_dir=args.output,
        remote=args.remote,
        expected_repo=args.expected_repo,
        branch=args.branch,
        message=args.message,
        repositories=args.repository,
        publish_repositories=args.publish_repository,
        evidence_file=args.evidence,
        push=args.push,
    )


if __name__ == "__main__":
    try:
        main()
    except StagingSmokeError as exc:
        print(f"Staging smoke error: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
