FULL_REPO_NAME_RE = re.compile(
    r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?/[A-Za-z0-9_.-]{1,100}$"
)


class StagingSmokeError(RuntimeError):
    """Raised when the staging smoke tree cannot be prepared or published."""


@dataclass(frozen=True)
class StagingSmokeResult:
    output_dir: Path
    evidence_file: Path
    published_commit: str | None
    record: dict[str, Any]


def _run(args: list[str], cwd: Path, *, env: dict[str, str] | None = None) -> None:
    # Every caller supplies a fixed git executable and an argument vector.
    subprocess.run(  # nosec B603
        args,
        cwd=cwd,
        env=env,
        check=True,
    )


def _output(args: list[str], cwd: Path) -> str:
    # Every caller supplies a fixed git executable and an argument vector.
    return subprocess.check_output(  # nosec B603
        args,
        cwd=cwd,
        text=True,
        stderr=subprocess.DEVNULL,
    ).strip()


def _git_value(*args: str) -> str:
    try:
        return _output(["git", *args], ROOT)
    except (subprocess.CalledProcessError, FileNotFoundError):
        return ""


def _utc_now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _split_repository_values(values: list[str]) -> list[str]:
    repositories: list[str] = []
    seen: set[str] = set()
    for value in values:
        for repository in re.split(r"[\s,]+", value.strip()):
            if not repository:
                continue
            if not FULL_REPO_NAME_RE.fullmatch(repository):
                raise StagingSmokeError(
                    "Staging repositories must be full GitHub names like "
                    + f"'owner/repo', got {repository!r}."
                )
            if repository not in seen:
                repositories.append(repository)
                seen.add(repository)
    return repositories


def resolve_repositories(
    repositories: list[str],
    publish_repositories: list[str],
) -> tuple[list[str], list[str]]:
    collect = _split_repository_values(repositories) or list(DEFAULT_REPOSITORIES)
    publish = _split_repository_values(publish_repositories) or list(collect)
    missing = sorted(set(publish) - set(collect))
    if missing:
        raise StagingSmokeError(
            "Publish repositories must be a subset of collect repositories: "
            + ", ".join(missing)
        )
    if len(publish) > 8:
        raise StagingSmokeError("The staging dashboard publish list must contain at most 8 repos.")
    return collect, publish


def _write_staging_config(
    output_dir: Path,
    *,
    collect_repositories: list[str],
    publish_repositories: list[str],
) -> None:
    config = {
        "i_have_read_the_readme": True,
        "data_mode": "encrypted",
        "publish_pages_dashboard": True,
        "publish_readme_dashboard": False,
        "artifact_retention_days": 90,
        "use_github_app": False,
        "auto_doctor_every_n_days": 0,
        "collect": {"repositories": collect_repositories},
        "publish": {"repositories": publish_repositories},
    }
    header = "\n".join(
        [
            "# Generated by scripts/staging_smoke.py for the copied-repository "
            + "staging smoke scenario.",
            "# This config intentionally exercises encrypted retained data, "
            + "GitHub Pages, and no README dashboard.",
        ]
    ) + "\n"
    (output_dir / "config.yaml").write_text(
        header + yaml.safe_dump(config, sort_keys=False),
        encoding="utf-8",
    )


def _read_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key] = value
    return values


def _validate_generated_config(output_dir: Path) -> dict[str, str]:
    env_file = output_dir / ".tmp-github-env"
    summary_file = output_dir / ".tmp-github-step-summary"
    env = {
        **os.environ,
        "GITHUB_ENV": str(env_file),
        "GITHUB_STEP_SUMMARY": str(summary_file),
        "GITHUB_REPOSITORY": DEFAULT_EXPECTED_REPO,
        "REPOSITORY_PRIVATE": "false",
    }
    # The current interpreter runs a fixed resolver path in the generated tree.
    result = subprocess.run(  # nosec B603
        [sys.executable, ".github/scripts/resolve-reponomics-config.py"],
        cwd=output_dir,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode != 0:
        for path in (env_file, summary_file):
            path.unlink(missing_ok=True)
        raise StagingSmokeError(
            "Generated staging config failed the copied-repository resolver:\n"
            + result.stderr.strip()
        )
    resolved = _read_env_file(env_file)
    for path in (env_file, summary_file):
        path.unlink(missing_ok=True)
    expected = {
        "REPONOMICS_SETUP_COMPLETE": "false",
        "DATA_MODE": "encrypted",
        "PUBLISH_PAGES_DASHBOARD": "true",
        "PUBLISH_README_DASHBOARD": "false",
        "USE_GITHUB_APP": "false",
        "COLLECTION_AUTH_MODE": "pat",
    }
    mismatches = {
        key: resolved.get(key)
        for key, value in expected.items()
        if resolved.get(key) != value
    }
    if mismatches:
        raise StagingSmokeError(f"Generated staging config resolved unexpectedly: {mismatches}")
    return resolved


def _build_record(
    *,
    output_dir: Path,
    remote: str,
    expected_repo: str,
    branch: str,
    collect_repositories: list[str],
    publish_repositories: list[str],
    resolved_config: dict[str, str],
) -> dict[str, Any]:
    contract = template_contract.load_contract()
    return {
        "schema_version": 1,
        "scenario": SCENARIO_NAME,
        "generated_at": _utc_now(),
        "source": {
            "repository": contract.action_repository,
            "commit": _git_value("rev-parse", "HEAD") or "unknown",
            "template_version": contract.template_version,
            "accepted_action": {
                "repository": contract.accepted_action.repository,
                "tag": contract.accepted_action.tag,
                "sha": contract.accepted_action.sha,
                "default_ref": contract.accepted_action.default_ref,
            },
        },
        "target": {
            "remote": remote,
            "expected_repo": expected_repo,
            "branch": branch,
        },
        "config": {
            "data_mode": "encrypted",
            "publish_pages_dashboard": True,
            "publish_readme_dashboard": False,
            "artifact_retention_days": 90,
            "use_github_app": False,
            "collection_auth_mode": "pat",
            "resolved": resolved_config,
        },
        "repositories": {
            "collect": collect_repositories,
            "publish": publish_repositories,
        },
        "operator_requirements": [
            "Target repository is public.",
            "GitHub Pages source is set to GitHub Actions.",
            "Repository secret COLLECTION_TOKEN is set to a low-scope token "
            + "that can read the selected public repositories.",
            "Repository secret DASHBOARD_SECRET_DO_NOT_REPLACE is set and retained.",
            "Run the generated Setup workflow before Collect and Publish.",
            "Unlock the deployed Pages dashboard in a browser with "
            + "DASHBOARD_SECRET_DO_NOT_REPLACE.",
        ],
        "output_dir": output_dir.as_posix(),
    }


def _write_record(output_dir: Path, record: dict[str, Any]) -> Path:
    path = output_dir / STAGING_RECORD
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def _repo_slug(expected_repo: str) -> str:
    slug = expected_repo.removesuffix(".git").strip("/")
    return slug or DEFAULT_EXPECTED_REPO


